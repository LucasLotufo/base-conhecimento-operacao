-- A tabela e as permissões abaixo são para os atalhos da seção "Sites úteis".

create table if not exists public.sites (
  id bigint generated by default as identity primary key,
  name text not null,
  url text not null,
  category text not null default '',
  description text not null default '',
  created_at timestamptz not null default now()
);

alter table public.sites enable row level security;

-- Leitura pública para que os sites apareçam para todos os visitantes.
drop policy if exists "Sites visíveis para todos" on public.sites;
create policy "Sites visíveis para todos"
  on public.sites for select
  to anon, authenticated
  using (true);

-- Alterações permitidas apenas para usuários autenticados (administradores que entraram no site).
drop policy if exists "Administradores podem inserir sites" on public.sites;
create policy "Administradores podem inserir sites"
  on public.sites for insert
  to authenticated
  with check (auth.uid() is not null);

drop policy if exists "Administradores podem editar sites" on public.sites;
create policy "Administradores podem editar sites"
  on public.sites for update
  to authenticated
  using (auth.uid() is not null)
  with check (auth.uid() is not null);

drop policy if exists "Administradores podem excluir sites" on public.sites;
create policy "Administradores podem excluir sites"
  on public.sites for delete
  to authenticated
  using (auth.uid() is not null);

grant select on public.sites to anon, authenticated;
grant insert, update, delete on public.sites to authenticated;
grant usage, select on sequence public.sites_id_seq to authenticated;
